"""Render frozen loss-comparison results as PNG, Markdown, and offline HTML."""

from __future__ import annotations

import base64
import html
import os
import tempfile
from pathlib import Path

import pandas as pd



def write_comparison_chart(report: dict, directory: Path) -> Path:
    """Show paired seeds; chart baselines use the same validation rows."""
    os.environ.setdefault("MPLCONFIGDIR", str(Path(tempfile.gettempdir()) / "fpl-ai-matplotlib"))
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    figure, axes = plt.subplots(2, 2, figsize=(11, 7), layout="constrained")
    metrics = [("rmse", "Validation RMSE · selects the loss", "Points"),
               ("mae", "Validation MAE", "Points"),
               ("top_k_actual_points", f"Actual points of predicted top {report['ranking_top_k']} · mean per week", "Points"),
               ("prediction_std", "Spread of player predictions", "Standard deviation (points)")]
    baseline = report["baseline"]
    baseline_top_points = sum(week["ranking"]["actual_points_total"] for week in baseline["per_gameweek"]) / len(baseline["per_gameweek"])
    baseline_values = {**baseline["metrics"], "top_k_actual_points": baseline_top_points,
                       "prediction_std": baseline["prediction_spread"]["std"]}
    for axis, (metric, title, ylabel) in zip(axes.flat, metrics):
        for loss, color in [("huber", "#c65b31"), ("mse", "#207a73")]:
            values = [next(run["summary_metrics"][metric] for run in report["runs"]
                           if run["loss"] == loss and run["seed"] == seed) for seed in report["seeds"]]
            axis.plot(range(len(values)), values, "o-", color=color, label=loss.upper())
        axis.axhline(baseline_values[metric], color="#666666", linestyle="--", label="Rolling-points baseline")
        if metric == "prediction_std":
            axis.axhline(report["actual_spread"]["std"], color="#8765ae", linestyle=":", label="Actual points spread")
        axis.set(title=title, xlabel="Paired seed", ylabel=ylabel)
        axis.set_xticks(range(len(report["seeds"])), labels=[str(seed) for seed in report["seeds"]])
        axis.grid(alpha=0.2)
        axis.legend(fontsize=8)
    figure.suptitle(f"Train GW{report['train_gameweeks']} · validate GW{report['validation_gameweeks']} · each run selects its epoch by RMSE")
    path = directory / "comparison.png"
    figure.savefig(path, dpi=160)
    plt.close(figure)
    return path


def summary_markdown(report: dict) -> str:
    """Generate the result record from measured values, including limitations."""
    lines = ["# Huber versus MSE: exploratory validation comparison", "",
             "Generated by `.venv/bin/python -m src.models.compare_losses`.", "",
             f"Train GW{report['train_gameweeks']} ({report['train_rows']} rows); validate GW{report['validation_gameweeks']} ({report['validation_rows']} rows).",
             f"Architecture: {len(report['input_columns'])} → " + " → ".join(map(str, report['base_options']['hidden_layers'])) + " → 1.",
             f"Seeds: {report['seeds']}. Epoch selection: validation RMSE. Loss selection: mean RMSE across seeds.", "",
             "| Loss | Mean RMSE ± seed std | Mean MAE ± seed std | Top-k actual points ± seed std | Prediction std ± seed std |",
             "|---|---:|---:|---:|---:|"]
    for loss in report["losses"]:
        metrics = report["comparison"]["by_loss"][loss]
        cells = [f"{metrics[key]['mean']:.3f} ± {metrics[key]['std']:.3f}"
                 for key in ["rmse", "mae", "top_k_actual_points", "prediction_std"]]
        lines.append(f"| {loss.upper()} | " + " | ".join(cells) + " |")
    baseline = report["baseline"]["metrics"]
    lines.extend(["", f"Rolling-points baseline: RMSE **{baseline['rmse']:.3f}**, MAE **{baseline['mae']:.3f}**.",
                  f"Preferred loss on this split: **{report['comparison']['preferred_loss'] or 'tie'}**. No model was promoted.",
                  "", report["comparison"]["std_definition"], "",
                  "| Loss | Seed | Selected epoch | Epochs run | RMSE | MAE | Top-k actual points | Prediction std |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|"])
    for run in report["runs"]:
        metrics = run["summary_metrics"]
        lines.append(f"| {run['loss']} | {run['seed']} | {run['best_epoch']} | {run['epochs_run']} | " +
                     " | ".join(f"{metrics[key]:.3f}" for key in ["rmse", "mae", "top_k_actual_points", "prediction_std"]) + " |")
    lines.extend(["", "Paired differences (MSE RMSE − Huber RMSE; negative favors MSE):", ""])
    lines.extend(f"- Seed {pair['seed']}: {pair['mse_minus_huber_rmse']:+.4f}." for pair in report["comparison"]["paired_differences"])
    lines.extend(["", "Limitations:", ""])
    lines.extend(f"- {limitation}" for limitation in report["limitations"])
    return "\n".join(lines) + "\n"


def write_loss_report(report: dict, predictions: pd.DataFrame, directory: Path) -> None:
    """Build a self-contained chart and searchable table; escape display labels."""
    chart = write_comparison_chart(report, directory)
    (directory / "results.md").write_text(summary_markdown(report))
    summaries = []
    for loss in report["losses"]:
        metrics = report["comparison"]["by_loss"][loss]
        summaries.append(f"<tr><th>{html.escape(loss.upper())}</th>" + "".join(
            f"<td>{metrics[key]['mean']:.3f} ± {metrics[key]['std']:.3f}</td>"
            for key in ["rmse", "mae", "top_k_actual_points", "prediction_std"]) + "</tr>")
    run_rows = []
    for run in report["runs"]:
        run_rows.append(f"<tr><td>{html.escape(run['loss'])}</td><td>{run['seed']}</td><td>{run['best_epoch']}</td><td>{run['epochs_run']}</td>" +
                        "".join(f"<td>{run['summary_metrics'][key]:.3f}</td>" for key in ["rmse", "mae", "top_k_actual_points", "prediction_std"]) + "</tr>")
    prediction_rows = []
    columns = ["loss", "seed", "gameweek", "element_id", "player_name", report["target"], "predicted_points", "baseline_points", "nn_error"]
    for values in predictions[columns].itertuples(index=False, name=None):
        cells = [f"<td>{html.escape(str(value))}</td>" if i in [0, 4] else
                 f'<td data-value="{float(value)}">{float(value):.2f}</td>' if i >= 5 else
                 f'<td data-value="{int(value)}">{int(value)}</td>' for i, value in enumerate(values)]
        prediction_rows.append(f'<tr data-run="{html.escape(str(values[0]))}_seed{int(values[1])}">' + "".join(cells) + "</tr>")
    template = (Path(__file__).resolve().parent / "templates/loss_comparison.html").read_text()
    replacements = {
        "{{CONTEXT}}": html.escape(f"Train GW{report['train_gameweeks']} ({report['train_rows']} rows); validate GW{report['validation_gameweeks']} ({report['validation_rows']} rows)."),
        "{{PREFERRED}}": html.escape(str(report["comparison"]["preferred_loss"] or "tie")),
        "{{SUMMARY_ROWS}}": "".join(summaries), "{{RUN_ROWS}}": "".join(run_rows),
        "{{PREDICTION_ROWS}}": "".join(prediction_rows),
        "{{RUN_OPTIONS}}": "".join(f'<option value="{html.escape(run["run_id"])}">{html.escape(run["run_id"])}</option>' for run in report["runs"]),
        "{{CHART}}": base64.b64encode(chart.read_bytes()).decode("ascii"),
        "{{BASELINE}}": f"RMSE {report['baseline']['metrics']['rmse']:.3f}; MAE {report['baseline']['metrics']['mae']:.3f}",
        "{{LIMITATIONS}}": "".join(f"<li>{html.escape(item)}</li>" for item in report["limitations"]),
        "{{STD_DEFINITION}}": html.escape(report["comparison"]["std_definition"]),
    }
    for key, value in replacements.items():
        template = template.replace(key, value)
    (directory / "report.html").write_text(template)
